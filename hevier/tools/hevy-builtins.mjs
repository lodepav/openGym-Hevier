#!/usr/bin/env node
// Writes frontend/src/hevier/lib/hevy-builtins.js: Hevy's built-in exercise templates (id, title,
// type), read from the hevy.com web app's _app bundle, where the web app keeps them. The export to
// Hevy's private web API (hevier/DECISIONS.md D138) has no list call for them; the official API
// that had one needs Pro. Run it again when Hevy adds exercises:
//   node hevier/tools/hevy-builtins.mjs            (fetches hevy.com)
//   node hevier/tools/hevy-builtins.mjs app.js     (a saved bundle)
import { readFileSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'

const OUT = fileURLToPath(new URL('../../frontend/src/hevier/lib/hevy-builtins.js', import.meta.url))
const UA = { 'user-agent': 'Mozilla/5.0 (X11; Linux x86_64)' }

async function bundle(path) {
  if (path) return readFileSync(path, 'utf8')
  const home = await (await fetch('https://hevy.com/', { headers: UA })).text()
  const js = home.match(/\/_next\/static\/chunks\/pages\/_app-[a-f0-9]+\.js/i)?.[0]
  if (!js) throw new Error('no _app bundle on hevy.com')
  const res = await fetch('https://hevy.com' + js, { headers: UA })
  if (!res.ok) throw new Error('bundle: http ' + res.status)
  return res.text()
}

/** Each built-in template in the bundle: { id, title, type }, in the bundle's order, one per id. */
export function parseBuiltins(js) {
  const out = new Map()
  const starts = [...js.matchAll(/\{"id":"([A-Z0-9]{8})"/g)]
  starts.forEach((m, i) => {
    const seg = js.slice(m.index, Math.min(starts[i + 1]?.index ?? js.length, m.index + 3000))
    const field = k => seg.match(new RegExp(`"${k}":"((?:[^"\\\\]|\\\\.)*)"`))?.[1]
    const title = field('title'), type = field('exercise_type')
    if (title && type && !out.has(m[1])) out.set(m[1], { id: m[1], title: JSON.parse(`"${title}"`), type })
  })
  return [...out.values()]
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const list = parseBuiltins(await bundle(process.argv[2]))
  if (list.length < 300) throw new Error('only ' + list.length + ' templates found: the bundle changed?')
  const rows = list.map(t => '  ' + JSON.stringify([t.id, t.title, t.type]) + ',').join('\n')
  writeFileSync(OUT, `// AUTO-GENERATED by hevier/tools/hevy-builtins.mjs from hevy.com's web bundle; do not edit by hand.
// Hevy's built-in exercise templates as [id, title, exercise_type] (hevier/DECISIONS.md D138).
// ${list.length} templates.
export const HEVY_BUILTINS = [
${rows}
]
`)
  console.log('wrote', list.length, 'templates to', OUT)
}
